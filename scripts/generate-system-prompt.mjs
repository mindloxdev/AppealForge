// Regenerates src/lib/ai/system-prompt.ts from docs/system-prompt.txt so the
// shipped prompt is verbatim by construction. Run after editing the spec copy.
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

const prompt = readFileSync("docs/system-prompt.txt", "utf8")
  .replace(/\r\n/g, "\n")
  .replace(/\n+$/, "");
const sha = createHash("sha256").update(prompt).digest("hex");

writeFileSync(
  "src/lib/ai/system-prompt.ts",
  [
    "/**",
    " * The appeal-letter system prompt, used verbatim.",
    " *",
    " * GENERATED from docs/system-prompt.txt by scripts/generate-system-prompt.mjs.",
    " * Do not edit this file, and do not reword the prompt: tests/unit/system-prompt.test.ts",
    " * asserts that the string below still hashes to SYSTEM_PROMPT_SHA256.",
    " */",
    `export const SYSTEM_PROMPT = ${JSON.stringify(prompt)};`,
    "",
    `export const SYSTEM_PROMPT_SHA256 = ${JSON.stringify(sha)};`,
    "",
  ].join("\n"),
  "utf8",
);

console.log(`system prompt: ${prompt.length} chars, sha256 ${sha}`);
